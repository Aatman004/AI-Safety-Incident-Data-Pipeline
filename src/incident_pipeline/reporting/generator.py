"""Briefing and trend report generator for AI safety intelligence."""

import json
from datetime import datetime
from pathlib import Path

from incident_pipeline.models import SeverityLevel
from incident_pipeline.storage.database import IncidentDatabase


class SafetyReportGenerator:
    """Generates structured intelligence reports from ingested safety records."""

    def __init__(self, db: IncidentDatabase):
        self.db = db

    def generate_markdown(self, title: str = "AI Safety Incident & Research Briefing") -> str:
        """Generate a comprehensive Markdown briefing report."""
        stats = self.db.get_statistics()
        records = self.db.get_all(limit=100)

        critical_records = [
            r for r in records if r.severity in (SeverityLevel.CRITICAL, SeverityLevel.HIGH)
        ]
        now_str = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")

        lines: list[str] = [
            f"# {title}",
            f"**Generated:** {now_str} | **Total Records Tracked:** {stats['total_records']}",
            "",
            "## 1. Executive Safety Overview",
            "This briefing synthesizes tracked preprints, empirical failure modes, and vulnerability disclosures across global AI safety research and incident databases.",
            "",
            "### Risk Category Breakdown",
            "| Threat Category | Tracked Records | Share |",
            "|---|:---:|:---:|",
        ]

        total = max(1, stats["total_records"])
        for cat, count in stats.get("by_category", {}).items():
            pct = (count / total) * 100
            readable_cat = cat.replace("_", " ").title()
            lines.append(f"| **{readable_cat}** | `{count}` | `{pct:.1f}%` |")

        lines.extend(
            [
                "",
                "### Severity Distribution",
                "| Severity Level | Incidents |",
                "|---|:---:|",
            ]
        )
        for sev, count in stats.get("by_severity", {}).items():
            lines.append(f"| `{sev.upper()}` | `{count}` |")

        lines.extend(
            [
                "",
                "## 2. High-Severity & Critical Findings",
            ]
        )

        if critical_records:
            for rec in critical_records[:5]:
                primary = (
                    rec.risk_categories[0].value.replace("_", " ").title()
                    if rec.risk_categories
                    else "General"
                )
                authors_str = ", ".join(rec.authors[:3]) if rec.authors else "Unspecified Authors"
                lines.extend(
                    [
                        f"### [{rec.title}]({rec.url})",
                        f"- **Source:** `{rec.source.value.upper()}` | **Severity:** `{rec.severity.value.upper()}` | **Category:** `{primary}`",
                        f"- **Authors:** {authors_str} | **Published:** {rec.published_at.strftime('%Y-%m-%d')}",
                        f"- **Summary:** {rec.summary}",
                        f"- **Tags:** {', '.join([f'`{t}`' for t in rec.tags]) if rec.tags else '`none`'}",
                        "",
                    ]
                )
        else:
            lines.append("No critical severity incidents flagged in the current dataset.\n")

        lines.extend(
            [
                "## 3. Recent Research Preprints & Reports",
                "| Date | Title | Category | Source |",
                "|---|---|---|---|",
            ]
        )

        for rec in records[:15]:
            cat_display = (
                rec.risk_categories[0].value.replace("_", " ") if rec.risk_categories else "safety"
            )
            short_title = rec.title[:65] + "..." if len(rec.title) > 65 else rec.title
            lines.append(
                f"| {rec.published_at.strftime('%Y-%m-%d')} | [{short_title}]({rec.url}) | `{cat_display}` | `{rec.source.value}` |"
            )

        lines.extend(
            [
                "",
                "---",
                "*Report generated by AI Safety Incident & Threat Intelligence Pipeline (Aatman Gupta)*",
            ]
        )

        return "\n".join(lines)

    def generate_json(self) -> str:
        """Export full intelligence state as structured JSON."""
        stats = self.db.get_statistics()
        records = [r.model_dump(mode="json") for r in self.db.get_all(limit=500)]
        payload = {
            "metadata": {
                "generated_at": datetime.utcnow().isoformat(),
                "total_records": stats["total_records"],
            },
            "statistics": stats,
            "records": records,
        }
        return json.dumps(payload, indent=2)

    def export_report(self, output_path: str | Path, format_type: str = "markdown") -> None:
        """Write the briefing report to the designated filepath."""
        path = Path(output_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        content = (
            self.generate_markdown() if format_type.lower() == "markdown" else self.generate_json()
        )
        path.write_text(content, encoding="utf-8")
